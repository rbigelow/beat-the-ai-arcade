import { useState } from 'react'
import GameHeader from '../components/GameHeader.jsx'
import GameComplete from '../components/GameComplete.jsx'
import BehindTheScenes from '../components/BehindTheScenes.jsx'
import { HUMAN_OR_AI_ROUNDS } from '../data/humanOrAIData.js'
import { playSfx } from '../utils/sfx.js'

const TOTAL = HUMAN_OR_AI_ROUNDS.length

export default function HumanOrAI({ game, onBack, onScore }) {
  const [round, setRound] = useState(0)
  const [choice, setChoice] = useState(null)
  const [score, setScore] = useState(0)
  const [finished, setFinished] = useState(false)

  const current = HUMAN_OR_AI_ROUNDS[round]
  const correct = choice === current.aiIs

  const choose = (letter) => {
    if (choice) return
    setChoice(letter)
    const isRight = letter === current.aiIs
    playSfx(isRight ? 'correct' : 'incorrect')
    if (isRight) setScore((s) => s + 1)
  }

  const next = () => {
    if (round + 1 >= TOTAL) {
      setFinished(true)
      onScore?.(score, TOTAL)
      return
    }
    setRound(round + 1)
    setChoice(null)
  }

  const restart = () => {
    setRound(0)
    setChoice(null)
    setScore(0)
    setFinished(false)
  }

  const stages = [
    { label: 'INPUT', detail: 'Two passages of the same kind (A and B)' },
    { label: 'PROCESSING', detail: 'You look for style patterns' },
    { label: 'GUIDE', detail: 'Clues: generic wording, buzzwords, tidy structure, no personal detail' },
    { label: 'DECISION', detail: 'You choose which one is AI-generated' },
    { label: 'RESULT', detail: 'The answer and explanation are revealed' },
  ]

  return (
    <div className="space-y-8">
      <GameHeader game={game} onBack={onBack} badge={{ kind: 'info', title: 'AI LITERACY ACTIVITY', detail: 'No AI model runs in this game' }} />
      {finished ? (
        <GameComplete heading="AI DETECTIVE" title="YOUR SCORE" score={score} outOf={TOTAL} onPlayAgain={restart} onBack={onBack}>
          <p>Stylistic patterns can sometimes suggest AI-generated content, but style alone cannot reliably prove authorship.</p>
        </GameComplete>
      ) : (
        <section className="arcade-card p-6 sm:p-8" aria-live="polite">
          <div className="flex flex-wrap justify-between gap-2 text-xl font-black">
            <p>Round {round + 1} / {TOTAL}</p>
            <p className="text-georgian-yellow">Score: {score}</p>
          </div>
          <p className="mt-2 text-sm font-bold tracking-widest text-georgian-light-blue">{current.type.toUpperCase()}</p>
          <h2 className="mt-2 text-2xl font-black">Which one was generated by AI?</h2>
          <div className="mt-6 grid gap-6 md:grid-cols-2">
            {['A', 'B'].map((letter) => {
              const text = letter === 'A' ? current.a : current.b
              const isAi = current.aiIs === letter
              return (
                <button
                  key={letter}
                  type="button"
                  disabled={!!choice}
                  onClick={() => choose(letter)}
                  className={`rounded-3xl border-4 p-6 text-left text-lg disabled:cursor-default ${
                    choice ? (isAi ? 'border-georgian-green bg-georgian-green/10' : 'border-white/20') : 'border-georgian-light-blue/50 hover:border-georgian-light-blue'
                  } ${choice === letter ? 'ring-4 ring-georgian-yellow' : ''}`}
                  aria-label={`Option ${letter}${choice ? (isAi ? ': AI generated' : ': Human written') : ''}`}
                >
                  <span className="mb-2 flex items-center gap-2 text-2xl font-black">
                    {letter}
                    {choice && <span className="text-sm tracking-widest">{isAi ? '🤖 AI GENERATED' : '🧑 HUMAN'}</span>}
                  </span>
                  <span className="whitespace-pre-wrap">{text}</span>
                </button>
              )
            })}
          </div>
          {choice && (
            <div className="mt-6 rounded-3xl bg-black/30 p-6">
              <p className={`text-3xl font-black ${correct ? 'text-georgian-green' : 'text-georgian-orange'}`}>
                {correct ? '✓ CORRECT!' : '✗ NOT THIS TIME'}
              </p>
              <p className="mt-2 text-lg">{current.explanation}</p>
              <button type="button" className="btn btn-primary mt-4" onClick={next}>
                {round + 1 >= TOTAL ? 'SEE RESULTS' : 'NEXT ROUND'}
              </button>
            </div>
          )}
        </section>
      )}
      <BehindTheScenes
        summary="Generative AI writes by predicting likely next words, which can leave recognisable patterns. Here, you are the detector."
        stages={stages}
        activeIndex={finished ? 4 : choice ? 4 : 1}
        live={[{ label: 'Round', value: `${Math.min(round + 1, TOTAL)}/${TOTAL}` }, { label: 'Your score', value: score }]}
        details={{
          input: 'Two short texts. One was written by a person, one was produced by a generative AI.',
          processing: 'You compare wording, structure and detail. No software analyses the text.',
          model: 'There is no model in this activity. It is an AI literacy exercise about generative AI.',
          decision: 'You pick A or B.',
          confidence: 'Not applicable. Even experts cannot be fully certain from style alone.',
          failure: 'Humans can write polished text and AI can imitate casual style, so these clues are unreliable.',
        }}
        learnMore="AI-text detectors are known to make mistakes, so style alone cannot reliably prove authorship."
      />
    </div>
  )
}
